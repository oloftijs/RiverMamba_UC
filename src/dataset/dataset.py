import json
import torch
import numpy as np
from pathlib import Path
from torch.utils.data import Dataset


class SubwayDelayDataset(Dataset):
    """
    PyTorch Dataset loading pre-aggregated tensors.npz and chronological splits.
    Constructs spatio-temporal tensors [T, P, V] by slicing valid time bins.
    """
    def __init__(self, tensors_dir='tensors_out', split='train', delta_t=4, delta_t_f=7,
                 n_points=472, graph_order='dfs', nan_fill=0.0):
        super().__init__()
        self.tensors_dir = Path(tensors_dir)
        self.split = split
        self.delta_t = delta_t
        self.delta_t_f = delta_t_f
        self.n_points = n_points
        self.graph_order = graph_order
        self.nan_fill = nan_fill

        self._load_data()

    def _load_data(self):
        if not self.tensors_dir.exists():
            raise FileNotFoundError(f"Directory {self.tensors_dir} missing. Run build_tensors.py first.")

        # Load chronological splits
        with open(self.tensors_dir / 'splits.json', 'r') as f:
            self.splits_info = json.load(f)

        # Load aggregated metrics: shape [Total_Time_Bins, Total_Stations]
        npz = np.load(self.tensors_dir / 'tensors.npz')
        self.delay = np_to_tensor(npz['delay'], self.nan_fill)
        self.mask = torch.tensor(npz['mask'], dtype=torch.float32)

        self.bins_per_day = self.splits_info['bins_per_day']
        valid_days = self.splits_info['day_index_from_t0'].get(self.split, [])

        if not valid_days:
            print(f"Warning: No valid days found in splits.json for split '{self.split}'.")

        # Map out valid starting indices for sequence slicing
        self.valid_start_indices = []
        seq_len = self.delta_t + self.delta_t_f

        for day in valid_days:
            day_start_bin = day * self.bins_per_day
            # Ensure the full sequence (hist + forecast) fits within the boundaries of the day
            for b in range(day_start_bin, day_start_bin + self.bins_per_day - seq_len + 1):
                self.valid_start_indices.append(b)

    def __len__(self):
        return len(self.valid_start_indices)

    def __getitem__(self, idx):
        start_idx = self.valid_start_indices[idx]
        end_idx_hist = start_idx + self.delta_t
        end_idx_target = end_idx_hist + self.delta_t_f

        # x_dynamic features: [T, P, V_dyn] where V_dyn=2 (delay_s and observation_mask)
        hist_delay = self.delay[start_idx:end_idx_hist, :self.n_points]
        hist_mask = self.mask[start_idx:end_idx_hist, :self.n_points]
        x_dynamic = torch.stack([hist_delay, hist_mask], dim=-1)

        # x_static placeholder (Requires MTA data merge if static variables are used)
        V_stat = 5
        x_static = torch.zeros((self.n_points, V_stat), dtype=torch.float32)

        # Graph vertex order [P]
        graph_vertex_order = torch.arange(self.n_points, dtype=torch.long)

        # y_target future delays: [P, delta_t_f]
        target_delay = self.delay[end_idx_hist:end_idx_target, :self.n_points]
        y_target = target_delay.transpose(0, 1)

        return {
            'x_dynamic': x_dynamic,
            'x_static': x_static,
            'graph_vertex_order': graph_vertex_order,
            'y_target': y_target
        }


def np_to_tensor(arr, nan_fill):
    arr = np.nan_to_num(arr, nan=nan_fill)
    return torch.tensor(arr, dtype=torch.float32)